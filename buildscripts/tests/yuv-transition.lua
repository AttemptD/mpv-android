-- Exercise the transition itself, not just a paused frame after it settles.
local root = '/data/user/0/is.xyz.mpv.yuvtest/files/'
local function action(name, fn)
    mp.msg.info('TRANSITION ' .. name)
    fn()
end
mp.register_event('playback-restart', function()
    mp.msg.info('TRANSITION restarted ' .. tostring(mp.get_property('time-pos')))
end)
mp.register_event('file-loaded', function()
    mp.add_timeout(2, function() action('seek-forward', function()
        mp.commandv('seek', '12', 'absolute+exact') end) end)
    mp.add_timeout(4, function() action('seek-back', function()
        mp.commandv('seek', '2', 'absolute+exact') end) end)
    mp.add_timeout(6, function() action('HW', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec-copy') end) end)
    mp.add_timeout(8, function() action('HW+', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec') end) end)
    mp.add_timeout(10, function() action('seek-back-again', function()
        mp.commandv('seek', '1', 'absolute+exact') end) end)
    mp.add_timeout(12, function() action('HW-again', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec-copy') end) end)
    mp.add_timeout(14, function() action('HW+-again', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec') end) end)
    mp.add_timeout(16, function() action('pause', function()
        mp.set_property_native('pause', true) end) end)
    mp.add_timeout(18, function() action('paused-seek', function()
        mp.commandv('seek', '10', 'absolute+exact') end) end)
    mp.add_timeout(20, function() action('paused-HW', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec-copy') end) end)
    mp.add_timeout(22, function() action('paused-HW+', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec') end) end)
    mp.add_timeout(24, function() action('paused-SW', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'no') end) end)
    mp.add_timeout(27, function() action('paused-HW+-from-SW', function()
        mp.commandv('script-message-to', 'afuse_p5', 'set-hwdec', 'mediacodec') end) end)
    mp.add_timeout(30, function() action('resume', function()
        mp.set_property_native('pause', false) end) end)
    mp.add_timeout(33, function()
        mp.set_property_native('pause', true)
        mp.msg.info('TRANSITION complete')
        local f = assert(io.open(root .. 'yuv-transition.done', 'w'))
        f:write('complete'); f:close()
    end)
end)
